// Builds the private Peer Feedback files from the org chart roster.
//   node tools/build-peer-feedback.mjs <private folder OUTSIDE the repo>
// Writes into that folder:
//   PeerFeedback.gs   the whole Apps Script (roster, personal codes, cadre token + tools/peer-feedback/Code.gs)
//   codes.csv         one personal code per cadet
//   code-slips.html   printable slips to hand out (cut along the lines)
//   cadre-token.txt   the read token the Cadre page uses (goes into cadre/vault.json, never the repo)
// Rerunning keeps every existing code and the token, and only adds codes for new cadets.
// Peer groups: POC = AS300 + AS400 + Graybeards, GMC = AS200 + AS250 + AS500, AS100.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { randomInt, randomBytes } from "node:crypto";
import path from "node:path";

const outDir = process.argv[2];
if (!outDir) { console.error("usage: node tools/build-peer-feedback.mjs <private folder outside the repo>"); process.exit(1); }
if (path.resolve(outDir).startsWith(path.resolve("."))) { console.error("Refusing: the output folder must be outside the repo (the codes are private)."); process.exit(1); }
mkdirSync(outDir, { recursive: true });

const DUE = "2026-11-20T17:00:00-06:00"; // 1700 Central, Fri 20 Nov 2026
const GROUP = { AS300: "poc", AS400: "poc", Graybeard: "poc", AS200: "gmc", AS250: "gmc", AS500: "gmc", AS100: "as100" };
const GROUP_LABEL = { poc: "POC", gmc: "AS 200 / 250 / 500", as100: "AS 100" };

// The shared roster (data/roster.js): people, seats, flights.
const ROSTER_DATA = (() => { const w = {}; new Function("window", readFileSync("data/roster.js", "utf8"))(w); return w.D250_ROSTER; })();
const people = Object.entries(ROSTER_DATA.people)
  .map(([key, [last, first, cls]]) => ({ key, name: first ? `${last}, ${first}` : last, cls }))
  .filter(p => GROUP[p.cls]).map(p => ({ ...p, group: GROUP[p.cls] }))
  .sort((a, b) => a.name.localeCompare(b.name));

// Keep earlier codes and the token.
const ALPHA = "ABCDEFGHJKMNPQRSTUVWXYZ23456789"; // no 0/O, 1/I/L
const codesFile = path.join(outDir, "codes.csv"), tokenFile = path.join(outDir, "cadre-token.txt");
const old = {};
if (existsSync(codesFile)) for (const line of readFileSync(codesFile, "utf8").split(/\r?\n/).slice(1)) {
  const cells = line.match(/("([^"]|"")*"|[^,]*)(,|$)/g)?.map(c => c.replace(/,$/, "").replace(/^"|"$/g, "").replace(/""/g, '"')) || [];
  if (cells[0] && cells[4]) old[cells[0]] = cells[4];
}
const used = new Set(Object.values(old));
const newCode = () => { let c; do { c = Array.from({ length: 8 }, () => ALPHA[randomInt(ALPHA.length)]).join(""); c = c.slice(0, 4) + "-" + c.slice(4); } while (used.has(c)); used.add(c); return c; };
let added = 0;
for (const p of people) { p.code = old[p.key] || (added++, newCode()); }
const token = existsSync(tokenFile) ? readFileSync(tokenFile, "utf8").trim() : randomBytes(24).toString("base64url");

const q = s => /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
writeFileSync(codesFile, "Cadet key,Cadet,Class,Peer group,Code\n" + people.map(p => [p.key, p.name, p.cls, GROUP_LABEL[p.group], p.code].map(q).join(",")).join("\n") + "\n");
writeFileSync(tokenFile, token + "\n");

const roster = people.map(({ key, name, cls, group, code }) => ({ key, name, cls, group, code }));
const gs = `/* Storm HQ Peer Feedback. GENERATED by tools/build-peer-feedback.mjs on ${new Date().toISOString().slice(0, 10)}.
   PRIVATE: holds every cadet's personal code and the cadre read token. Never commit this file. */
var DUE = ${JSON.stringify(DUE)};
var CADRE_TOKEN = ${JSON.stringify(token)};
var ROSTER = [
${roster.map(r => "  " + JSON.stringify(r)).join(",\n")}
];

` + readFileSync("tools/peer-feedback/Code.gs", "utf8");
writeFileSync(path.join(outDir, "PeerFeedback.gs"), gs);

// Each slip gets its own QR code: the page link with #code=<that cadet's code>, so scanning signs them in
// (the page reads the code after the #, which never leaves the phone, and then clears it from the address bar).
// Drawn as inline SVG so the slips print offline.
// Needs qrcode-generator: npm i qrcode-generator, then run with NODE_PATH=<that folder>/node_modules.
const PAGE_URL = "https://captainrussell.github.io/det250/peer-feedback/";
let qrcode;
try { qrcode = (await import("node:module")).createRequire(import.meta.url)("qrcode-generator"); }
catch { console.error("qrcode-generator not found: npm i qrcode-generator and set NODE_PATH (see the comment above)"); process.exit(1); }
const qrSvgFor = p => { const q = qrcode(0, "M"); q.addData(`${PAGE_URL}#code=${p.code}`); q.make(); return q.createSvgTag({ cellSize: 2, margin: 0, scalable: true }); };

// Flights (code slips are grouped by flight): flights + flightsPoc members, plus each FLT/CC and FLT/CD seat.
const FLIGHT_NAMES = { afl: "Alpha", bfl: "Bravo", cfl: "Charlie", dfl: "Delta" };
const flightOf = {};
for (const list of [ROSTER_DATA.flights, ROSTER_DATA.flightsPoc]) for (const [fl, keys] of Object.entries(list)) for (const k of keys) flightOf[k] = fl;
for (const seat of ROSTER_DATA.seats) if (/^[abcd]f[ld]$/.test(seat.id) && seat.poc) flightOf[seat.poc[0]] ??= seat.id[0] + "fl";
const noFlight = people.filter(p => !flightOf[p.key]);
if (noFlight.length) console.warn("No flight found (slips go under No flight):", noFlight.map(p => p.name).join("; "));
const FLIGHT_ORDER = [...Object.keys(FLIGHT_NAMES), "none"];
const flightName = p => FLIGHT_NAMES[flightOf[p.key]] ? `${FLIGHT_NAMES[flightOf[p.key]]} Flight` : "No flight";

const esc = s => String(s).replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
// Org chart photo embedded in each slip (so the file stands alone), initials when there is no photo.
const photo = p => {
  const f = `org-chart/photos/${p.key}.jpg`;
  if (existsSync(f)) return `<img src="data:image/jpeg;base64,${readFileSync(f).toString("base64")}" alt="">`;
  const [last, first = ""] = p.name.split(", ");
  return `<span>${esc((first[0] || "") + (last[0] || ""))}</span>`;
};
// Each slip is credit card size (3.375 x 2.125 in): 2 across, 5 down = 10 per Letter page. Each flight starts a new page.
const slips = `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Peer Feedback codes · Storm HQ</title>
<style>
@page{size:letter;margin:.18in .5in}
*{box-sizing:border-box}
body{font:14px/1.3 system-ui,-apple-system,"Segoe UI",Roboto,Helvetica,Arial,sans-serif;margin:16px;color:#1b1b1d;-webkit-print-color-adjust:exact;print-color-adjust:exact}
h1{font-size:18px;margin:0 0 4px} p.note{margin:0 0 14px;color:#55565c}
h2{font-size:14px;margin:18px 0 6px}
.grid{display:grid;grid-template-columns:repeat(2,3.375in);grid-auto-rows:2.125in;gap:0;justify-content:center}
.slip{border:1px dashed #9a9aa2;padding:.12in .14in;break-inside:avoid;display:grid;grid-template-columns:.95in 1fr;grid-template-rows:auto 1fr;column-gap:.12in;overflow:hidden}
.ph{grid-row:1/3;width:.95in;height:1.19in;border-radius:6px;overflow:hidden;background:#e4e4e8;display:flex;align-items:center;justify-content:center;font:700 26px/1 system-ui,sans-serif;color:#55565c;align-self:center}
.ph img{width:100%;height:100%;object-fit:cover;display:block}
.top .n{font-weight:700;font-size:13px;line-height:1.2}.top .k{font-size:11px;color:#55565c}
.bot{display:flex;align-items:flex-end;gap:.08in;min-width:0}
.bot .w{flex:1;min-width:0}
.c{font:700 15px/1.2 ui-monospace,Menlo,Consolas,monospace;letter-spacing:.04em;color:#c8102e;white-space:nowrap}
.u{font-size:8.5px;color:#55565c;margin-top:3px;overflow-wrap:anywhere}
.q{width:.82in;height:.82in;flex:none}.q svg{width:100%;height:100%;display:block}
@media print{body{margin:0}h1,.note,h2{display:none}.grid+h2+.grid,.grid~.grid{break-before:page}}
</style></head><body>
<h1>Peer Feedback personal codes</h1><p class="note">Private. Each slip is credit card size: print at 100% (Actual size) and cut on the dashed lines. Grouped by flight; each flight starts on a new page. Due ${esc(new Date(DUE).toLocaleString("en-US", { timeZone: "America/Chicago", dateStyle: "medium", timeStyle: "short" }))} Central.</p>
${FLIGHT_ORDER.map(f => [f, people.filter(p => (flightOf[p.key] || "none") === f)]).filter(([, list]) => list.length).map(([f, list]) => `<h2>${esc(f === "none" ? "No flight" : FLIGHT_NAMES[f] + " Flight")}</h2><div class="grid">${list.map(p =>
  `<div class="slip"><div class="ph">${photo(p)}</div><div class="top"><div class="n">${esc(p.name)}</div><div class="k">${esc(p.cls)} · ${esc(flightName(p))}</div></div><div class="bot"><div class="w"><div class="c">${esc(p.code)}</div><div class="u">captainrussell.github.io/<wbr>det250/<wbr>peer-feedback</div></div><div class="q">${qrSvgFor(p)}</div></div></div>`).join("")}</div>`).join("")}
</body></html>`;
writeFileSync(path.join(outDir, "code-slips.html"), slips);

const count = g => people.filter(p => p.group === g).length;
console.log(`${people.length} cadets (POC ${count("poc")}, GMC ${count("gmc")}, AS100 ${count("as100")}); ${added} new code(s). Wrote ${outDir}`);
